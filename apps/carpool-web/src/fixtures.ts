export function demoPreview(id: string): TripPreview | null {
  const card = DEMO_TRIPS.find((t) => t.id === id);
  if (!card) return null;
  const seats =
    card.vehicle_type === 'sedan'
      ? [
          {
            id: 's-fp',
            position: 'front_passenger' as const,
            is_open: true,
            is_booked: card.id === 'demo-arm',
            label: card.id === 'demo-arm' ? 'บี' : undefined,
          },
          {
            id: 's-rl',
            position: 'rear_left' as const,
            is_open: true,
            is_booked: card.open_seats < card.bookable_seats,
            label: 'โก้',
          },
          {
            id: 's-rm',
            position: 'rear_middle' as const,
            is_open: true,
            is_booked: card.status === 'full',
          },
          {
            id: 's-rr',
            position: 'rear_right' as const,
            is_open: true,
            is_booked: card.status === 'full',
            label: card.status === 'full' ? 'คุณอ้อย' : undefined,
          },
        ]
      : [
          {
            id: 's-fp',
            position: 'front_passenger' as const,
            is_open: true,
            is_booked: false,
          },
          {
            id: 's-rl',
            position: 'rear_left' as const,
            is_open: true,
            is_booked: true,
            label: 'น้องบิ๋ว',
          },
          {
            id: 's-rr',
            position: 'rear_right' as const,
            is_open: true,
            is_booked: card.open_seats === 0,
          },
        ];
  return { ...card, seats };
}

